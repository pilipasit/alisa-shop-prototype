/* very small markdown: **bold** */
function rich(t) {
  const parts = String(t).split(/\*\*(.+?)\*\*/g);
  return parts.map((s,i) => i%2 ? <b key={i} style={{color:'var(--ink-900)'}}>{s}</b> : <React.Fragment key={i}>{s}</React.Fragment>);
}

function FillIn({ label }) {
  return (
    <div style={{ marginTop:8, background:'var(--pink-100)', border:'1px dashed var(--pink-500)',
      borderRadius:'var(--radius-md)', padding:'10px 12px', fontSize:13, fontWeight:700, color:'var(--pink-600)' }}>
      ⟨ Заповнити: {label} ⟩
    </div>
  );
}

